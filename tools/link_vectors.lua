-- Writes bridge/internal/link/testdata/vectors.txt: frames made by the
-- addon's encoder (TrailMate/core/Link.lua), which the bridge's Go tests
-- must read back exactly. A test on each side checks the file, so the two
-- encoders cannot drift apart.
--
-- Run it from the repository root (in the VM): lua tools/link_vectors.lua

local M = {}

local FRAMES = {
  { session = "1A2B3C4D", seq = 1, slot = 1, msg = 1, part = 1, count = 1, payload = "Mhola" },
  { session = "1A2B3C4D", seq = 2, slot = 1, msg = 2, part = 1, count = 2, payload = "M¿Qué hago en Grom'gol" },
  { session = "1A2B3C4D", seq = 3, slot = 41, msg = 2, part = 2, count = 2, payload = "?" },
  { session = "FFFFFFFF", seq = 16777215, slot = 1000, msg = 16777215, part = 64, count = 64,
    payload = "\0\1\2\127\128\254\255" },
}

local function hex(s)
  return (s:gsub(".", function(c)
    return ("%02x"):format(c:byte())
  end))
end

--- The file's text: "crc <hex input> <crc>" lines, then one line per frame:
--- action, session, seq, slot, msg, part, count and the payload in hex.
function M.text(Link)
  local out = { "# Generated by tools/link_vectors.lua: do not edit by hand." }
  for _, s in ipairs({ "", "123456789", "TrailMate" }) do
    out[#out + 1] = ("crc %s %d"):format(s == "" and "-" or hex(s), Link.crc32(s))
  end
  for _, f in ipairs(FRAMES) do
    out[#out + 1] = ("frame %s %s %d %d %d %d %d %s"):format(Link.action(f), f.session, f.seq, f.slot, f.msg, f.part,
      f.count, hex(f.payload))
  end
  return table.concat(out, "\n") .. "\n"
end

if arg and arg[0] and arg[0]:match("link_vectors%.lua$") then
  local ns = {}
  assert(loadfile("TrailMate/core/Link.lua"))("TrailMate", ns)
  local path = "bridge/internal/link/testdata/vectors.txt"
  local file = assert(io.open(path, "wb"))
  file:write(M.text(ns.Link))
  file:close()
  print(path)
end

return M
