-- Turns trail exports from the game's log into TrailMate/data/Routes.lua.
--
-- In the game: walk a city, then /tm trail export. The Log tab gets lines
-- "TMR1 3/12 <text>". Paste the whole Log tab into a text file and run, from
-- the repository root (in the VM):
--
--   lua tools/import_routes.lua <version> export1.txt [export2.txt ...]
--
-- Every file is read, its pieces put back in order, checked with
-- Trails.parse, and written as one entry. Existing entries are kept.

local Trails
do
  local ns = {}
  assert(loadfile("TrailMate/core/Trails.lua"))("TrailMate", ns)
  Trails = ns.Trails
end

--- The trail text in a pasted log: the pieces "TMR1 k/n text" joined in order.
local function readExport(path)
  local pieces, total = {}, nil
  for line in io.lines(path) do
    local k, n, chunk = line:match("TMR1 (%d+)/(%d+) (%S+)")
    if k then
      pieces[tonumber(k)] = chunk
      total = tonumber(n)
    end
  end
  assert(total, path .. ": no TMR1 lines found")
  for k = 1, total do
    assert(pieces[k], ("%s: piece %d of %d is missing"):format(path, k, total))
  end
  local text = table.concat(pieces, "", 1, total)
  local data = assert(Trails.parse(text), path .. ": not trail text")
  return text, #data.nodes, #data.links
end

local function existing(path)
  local entries = {}
  local file = io.open(path, "r")
  if file then
    -- Only the entries (one per line, quoted, with a comma), not the
    -- example in the header comment; and only real trail text.
    for line in file:lines() do
      local text = line:match('^%s*"(TMR1#[^"]*)",%s*$')
      if text and Trails.parse(text) then
        entries[#entries + 1] = text
      end
    end
    file:close()
  end
  return entries
end

local OUT = "TrailMate/data/Routes.lua"
local version = tonumber(arg[1])
assert(version and arg[2], "usage: lua tools/import_routes.lua <version> export1.txt [...]")

local entries = existing(OUT)
for i = 2, #arg do
  local text, dots, joins = readExport(arg[i])
  entries[#entries + 1] = text
  print(("%s: %d dots, %d joins"):format(arg[i], dots, joins))
end

local out = assert(io.open(OUT, "w"))
out:write([[
-- Ways through the capitals that ship with TrailMate, so a new player can
-- follow Orgrimmar's zigzag gate or Undercity's floors from the first day.
-- Each entry is trail text (core/Trails.lua, "TMR1#..."), walked in the game
-- and exported with /tm trail export. Generated by tools/import_routes.lua:
-- do not edit by hand. Raise the version when entries change, so players who
-- already have them get the new ones.

local _, ns = ...

ns.ROUTES = {
]])
out:write(("  version = %d,\n"):format(version))
for _, text in ipairs(entries) do
  out:write(('  "%s",\n'):format(text))
end
out:write("}\n")
out:close()
print(("%s: %d entries, version %d"):format(OUT, #entries, version))
