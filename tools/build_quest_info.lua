-- Builds TrailMate/data/QuestInfo.lua: for every quest of WoW Forever up to
-- level 60, who gives it, what it is about and who takes it back, so the
-- step preview (the magnifier) can show them for any quest: one of a route
-- made from the quest log, or one the player marks that no guide has. From
-- the Questie database for Forever (read with tools/questdb.lua), with the
-- 3D models of objects (see questdb.lua, loadModels). Runs in the VM only:
--
--   lua tools/build_quest_info.lua <questdb folder>

package.path = "tools/?.lua;" .. package.path
local Q = require("questdb")

local qdbDir = arg[1]
assert(qdbDir, "usage: lua tools/build_quest_info.lua <questdb folder>")
local db = Q.open(qdbDir .. "/QuestieDB_Forever.toc", qdbDir .. "/areaIdToUiMapId.lua")
Q.loadModels(db, qdbDir)

local MAX_LEVEL = 62 -- quests for level 60 characters go up to 62

local function quote(s)
  return ("%q"):format(s):gsub("\\\n", "\\n")
end

local ids = {}
for key in pairs(db.lines) do
  local id = key:match("^Quest%-(%d+)%-S$")
  if id then
    ids[#ids + 1] = tonumber(id)
  end
end
table.sort(ids)

-- Who starts or ends it: name, creature id, model file (an object).
local function who(field, id)
  local _, name, creature, model = Q.giver(db, Q.field(db, "Quest", id, field))
  return name, creature, model
end

local out = assert(io.open("TrailMate/data/QuestInfo.lua", "w"))
out:write([[
-- Who gives each quest of WoW Forever (up to level 60), what it is about
-- and who takes it back, for the step preview of any quest. Generated by
-- tools/build_quest_info.lua from the Questie database for Forever: do not
-- edit by hand.
--
-- [quest id] = { an, ac, am: who gives it (name, creature id, model file of
-- an object); dn, dc, dm, dd, dl: what it is about (the first creature or
-- object of its objectives; dd = true when it drops the item, dl = the item
-- looted from an object); tn, tc, tm: who takes it back }.

local _, ns = ...

ns.QUEST_INFO = {
]])
local count = 0
for _, id in ipairs(ids) do
  local level = Q.field(db, "Quest", id, Q.QUEST.questLevel)
  if type(level) == "number" and level <= MAX_LEVEL then
    local parts = {}
    local function put(key, v, fmt)
      if v ~= nil then
        parts[#parts + 1] = key .. " = " .. (fmt == "s" and quote(v) or tostring(v))
      end
    end
    local an, ac, am = who(Q.QUEST.startedBy, id)
    put("an", an, "s")
    put("ac", ac)
    put("am", am)
    local t = Q.targets(db, id)[1]
    if t then
      put("dn", t.n, "s")
      put("dc", t.c)
      put("dm", t.m)
      put("dd", t.d)
      put("dl", t.l)
    end
    local tn, tc, tm = who(Q.QUEST.finishedBy, id)
    put("tn", tn, "s")
    put("tc", tc)
    put("tm", tm)
    if #parts > 0 then
      out:write(("  [%d] = { %s },\n"):format(id, table.concat(parts, ", ")))
      count = count + 1
    end
  end
end
out:write("}\n")
out:close()
print(("%d quests written to TrailMate/data/QuestInfo.lua"):format(count))
